# Recovery utility for the existing QuickLabs instance. This is not the normal deployment path.
# Normal bootstrap: 01-ec2-user-data.sh. Later releases: infra/aws/deploy-release.sh via SSM.
#!/bin/bash
set -Eeuo pipefail
umask 077

APP_SHA="dafc89b4b804cddaa2f443a55b05d48ffa3bd921"
IMAGE="josvier-simple-bank-api:dafc89b4"
BASE="/opt/simple-bank"
RUNTIME_ENV="${BASE}/runtime.env"
BACKEND_ENV="${BASE}/backend.env"
IDENTITIES="${BASE}/aws-identities.json"
PROVISION="${BASE}/provision.py"
MONGO_CONTAINER="simple-bank-mongo"
API_CONTAINER="simple-bank-api"
MONGO_VOLUME="simple-bank-mongo-data"
NETWORK="simple-bank-net"
KEYFILE="${BASE}/mongo-keyfile"
PHASE="precheck"

log() { printf '%s\n' "$*"; }
fail() { log "REPAIR FAILED"; log "phase=${PHASE}"; log "reason=$*"; exit 1; }
trap 'ec=$?; if [ "$ec" -ne 0 ]; then log "REPAIR FAILED"; log "phase=${PHASE}"; log "exit=${ec}"; fi' ERR

[ "$(id -u)" -eq 0 ] || fail "run as root (sudo bash ...)"
systemctl is-active --quiet docker || fail "Docker service is not active"
[ -s "$RUNTIME_ENV" ] || fail "missing $RUNTIME_ENV"
[ -s "$BACKEND_ENV" ] || fail "missing $BACKEND_ENV"
[ -s "$PROVISION" ] || fail "missing $PROVISION"
docker volume inspect "$MONGO_VOLUME" >/dev/null 2>&1 || fail "missing Mongo volume $MONGO_VOLUME"
docker network inspect "$NETWORK" >/dev/null 2>&1 || fail "missing Docker network $NETWORK"
docker image inspect "$IMAGE" >/dev/null 2>&1 || fail "missing application image $IMAGE"

# Reuse the secrets generated by the original bootstrap. Never print them.
set -a
# shellcheck disable=SC1090
. "$RUNTIME_ENV"
set +a
: "${MONGO_ROOT_PASSWORD:?missing MONGO_ROOT_PASSWORD}"
: "${MONGO_APP_PASSWORD:?missing MONGO_APP_PASSWORD}"
: "${JWT_SECRET:?missing JWT_SECRET}"

log "repair_precheck=PASS"

set_env_value() {
  local key="$1" value="$2"
  python3 - "$BACKEND_ENV" "$key" "$value" <<'PY'
import pathlib, sys
path = pathlib.Path(sys.argv[1])
key, value = sys.argv[2], sys.argv[3]
lines = path.read_text(encoding="utf-8").splitlines()
out = []
found = False
for line in lines:
    if line.startswith(key + "="):
        out.append(f"{key}={value}")
        found = True
    else:
        out.append(line)
if not found:
    out.append(f"{key}={value}")
path.write_text("\n".join(out) + "\n", encoding="utf-8")
path.chmod(0o600)
PY
}

wait_mongo_ping() {
  local ok=0
  for _ in $(seq 1 90); do
    if docker exec -e MONGO_ROOT_PASSWORD="$MONGO_ROOT_PASSWORD" "$MONGO_CONTAINER" \
      bash -lc 'mongosh --quiet --host 127.0.0.1 --port 27017 -u root -p "$MONGO_ROOT_PASSWORD" --authenticationDatabase admin --eval "quit(db.runCommand({ping:1}).ok === 1 ? 0 : 1)"' \
      >/dev/null 2>&1; then
      ok=1
      break
    fi
    sleep 2
  done
  [ "$ok" -eq 1 ] || fail "Mongo did not become reachable"
}

wait_primary() {
  local ok=0
  for _ in $(seq 1 90); do
    if docker exec -e MONGO_ROOT_PASSWORD="$MONGO_ROOT_PASSWORD" "$MONGO_CONTAINER" \
      bash -lc 'mongosh --quiet --host 127.0.0.1 --port 27017 -u root -p "$MONGO_ROOT_PASSWORD" --authenticationDatabase admin --eval "quit(db.hello().isWritablePrimary === true ? 0 : 1)"' \
      >/dev/null 2>&1; then
      ok=1
      break
    fi
    sleep 2
  done
  [ "$ok" -eq 1 ] || fail "rs0 did not become PRIMARY"
}

start_api() {
  docker rm -f "$API_CONTAINER" >/dev/null 2>&1 || true
  docker run -d --name "$API_CONTAINER" \
    --network "$NETWORK" \
    --restart unless-stopped \
    --env-file "$BACKEND_ENV" \
    -p 8080:8080 \
    "$IMAGE" >/dev/null
}

wait_api() {
  local ready=""
  for _ in $(seq 1 90); do
    ready="$(curl -sS --fail --max-time 10 http://127.0.0.1:8080/api/public/ready 2>/dev/null || true)"
    if printf '%s' "$ready" | grep -q '"status":"UP"' \
      && printf '%s' "$ready" | grep -q '"environment":"production"' \
      && printf '%s' "$ready" | grep -q "$APP_SHA" \
      && curl -sS --fail --max-time 10 http://127.0.0.1:8080/api/public/health 2>/dev/null | grep -q '"status":"UP"' \
      && curl -sS --fail --max-time 10 http://127.0.0.1:8080/api/public/config 2>/dev/null | grep -q '"demoMode":false'; then
      log "health=PASS ready=PASS"
      return 0
    fi
    sleep 5
  done
  log "api_health=FAIL"
  docker ps --format '{{.Names}} {{.Status}} {{.Ports}}' || true
  if docker ps -a --format '{{.Names}}' | grep -qx "$API_CONTAINER"; then
    docker logs --tail 100 "$API_CONTAINER" 2>&1 | grep -Eiv 'mongodb(\+srv)?://|password|jwt|authorization:|bearer ' || true
  fi
  return 1
}

PHASE="stop-api"
docker rm -f "$API_CONTAINER" >/dev/null 2>&1 || true

PHASE="keyfile"
if [ ! -s "$KEYFILE" ]; then
  openssl rand -base64 512 | tr -d '\n' > "$KEYFILE"
fi
# Official mongo image uses uid/gid 999 for mongod.
chown 999:999 "$KEYFILE"
chmod 400 "$KEYFILE"

PHASE="mongo-replica-set"
# Recreate only the container; preserve the named data volume.
docker rm -f "$MONGO_CONTAINER" >/dev/null 2>&1 || true

docker run -d --name "$MONGO_CONTAINER" \
  --network "$NETWORK" \
  --restart unless-stopped \
  -v "$MONGO_VOLUME:/data/db" \
  -v "$KEYFILE:/etc/mongo-keyfile:ro" \
  -e MONGO_INITDB_ROOT_USERNAME=root \
  -e MONGO_INITDB_ROOT_PASSWORD="$MONGO_ROOT_PASSWORD" \
  mongo:7 \
  --replSet rs0 \
  --keyFile /etc/mongo-keyfile \
  --bind_ip_all >/dev/null

wait_mongo_ping

# Determine whether rs0 is already initialized. Exit 42 means NotYetInitialized.
# Capture this expected non-zero status inside an if so the global ERR trap does not fire.
if docker exec -e MONGO_ROOT_PASSWORD="$MONGO_ROOT_PASSWORD" "$MONGO_CONTAINER" \
  bash -lc 'mongosh --quiet --host 127.0.0.1 --port 27017 -u root -p "$MONGO_ROOT_PASSWORD" --authenticationDatabase admin --eval '\''try { const s=rs.status(); quit(s.ok === 1 ? 0 : 2); } catch (e) { if (e.code === 94 || e.codeName === "NotYetInitialized") quit(42); print(e.codeName || e.message); quit(3); }'\''' \
  >/dev/null 2>&1; then
  rs_rc=0
else
  rs_rc=$?
fi

if [ "$rs_rc" -eq 42 ]; then
  docker exec -e MONGO_ROOT_PASSWORD="$MONGO_ROOT_PASSWORD" "$MONGO_CONTAINER" \
    bash -lc 'mongosh --quiet --host 127.0.0.1 --port 27017 -u root -p "$MONGO_ROOT_PASSWORD" --authenticationDatabase admin --eval '\''const r=rs.initiate({_id:"rs0",members:[{_id:0,host:"simple-bank-mongo:27017"}]}); quit((r.ok===1 || r.codeName==="AlreadyInitialized") ? 0 : 1);'\''' \
    >/dev/null
elif [ "$rs_rc" -ne 0 ]; then
  fail "unable to read replica-set status"
fi

wait_primary
log "mongo_replica_set=PASS"

PHASE="mongo-user"
cat > "${BASE}/ensure-app-user.js" <<EOF
const appDb = db.getSiblingDB("simple_bank_aws");
if (appDb.getUser("simplebank_app") == null) {
  appDb.createUser({
    user: "simplebank_app",
    pwd: "${MONGO_APP_PASSWORD}",
    roles: [{ role: "readWrite", db: "simple_bank_aws" }]
  });
}
EOF
chmod 600 "${BASE}/ensure-app-user.js"
docker cp "${BASE}/ensure-app-user.js" "$MONGO_CONTAINER:/tmp/ensure-app-user.js" >/dev/null
docker exec -e MONGO_ROOT_PASSWORD="$MONGO_ROOT_PASSWORD" "$MONGO_CONTAINER" \
  bash -lc 'mongosh --quiet --host 127.0.0.1 --port 27017 -u root -p "$MONGO_ROOT_PASSWORD" --authenticationDatabase admin --file /tmp/ensure-app-user.js' \
  >/dev/null
docker exec "$MONGO_CONTAINER" rm -f /tmp/ensure-app-user.js >/dev/null 2>&1 || true
rm -f "${BASE}/ensure-app-user.js"

PHASE="mongo-transaction-smoke"
# Do not use a bespoke mongosh CRUD smoke here: shell collection/session APIs differ
# across mongosh versions. The application bootstrap below is the authoritative
# transaction integration test. Here we only assert that rs0 is writable PRIMARY.
wait_primary
log "mongo_transactions=READY_FOR_APP_TEST"

PHASE="backend-env"
mongo_scheme="mongodb"
MONGO_URI="${mongo_scheme}://simplebank_app:${MONGO_APP_PASSWORD}@simple-bank-mongo:27017/simple_bank_aws?authSource=simple_bank_aws&replicaSet=rs0"
set_env_value MONGODB_URI "$MONGO_URI"
set_env_value BOOTSTRAP_ADMIN_ENABLED false
set_env_value BOOTSTRAP_ADMIN_USERNAME ""
set_env_value DEMO_SEED_ENABLED false
set_env_value DEMO_SEED_RESET false
set_env_value APP_REVISION "$APP_SHA"
unset MONGO_URI

PHASE="api"
start_api
wait_api

# BOOTSTRAP_REQUIRED (exit 10) is expected on a first admin promotion.
PHASE="identity-prepare"
if python3 "$PROVISION" prepare; then
  prepare_status=0
else
  prepare_status=$?
fi

if [ "$prepare_status" -eq 10 ]; then
  PHASE="bootstrap-admin-on"
  set_env_value BOOTSTRAP_ADMIN_ENABLED true
  set_env_value BOOTSTRAP_ADMIN_USERNAME aws.admin
  start_api
  wait_api
  python3 "$PROVISION" confirm-admin

  PHASE="bootstrap-admin-off"
  set_env_value BOOTSTRAP_ADMIN_ENABLED false
  set_env_value BOOTSTRAP_ADMIN_USERNAME ""
  start_api
  wait_api
  python3 "$PROVISION" confirm-admin
  log "mongo_transactions=PASS"
elif [ "$prepare_status" -ne 0 ]; then
  fail "identity preparation failed with status $prepare_status"
else
  python3 "$PROVISION" confirm-admin
  log "mongo_transactions=PASS"
fi

# Safety: final state must always have bootstrap disabled.
set_env_value BOOTSTRAP_ADMIN_ENABLED false
set_env_value BOOTSTRAP_ADMIN_USERNAME ""

PHASE="customer"
python3 "$PROVISION" provision-customer
log "admin=PASS customer=PASS bootstrap=OFF demo_seed=OFF"

PHASE="persistence"
docker rm -f "$API_CONTAINER" >/dev/null 2>&1 || true
docker restart "$MONGO_CONTAINER" >/dev/null
wait_mongo_ping
wait_primary
start_api
wait_api
python3 "$PROVISION" confirm-admin
python3 "$PROVISION" provision-customer

PHASE="security-checks"
grep -q '^BOOTSTRAP_ADMIN_ENABLED=false$' "$BACKEND_ENV" || fail "bootstrap is not off"
grep -q '^BOOTSTRAP_ADMIN_USERNAME=$' "$BACKEND_ENV" || fail "bootstrap username is not blank"
grep -q '^DEMO_SEED_ENABLED=false$' "$BACKEND_ENV" || fail "demo seed is not off"
if docker port "$MONGO_CONTAINER" 27017/tcp 2>/dev/null | grep -q .; then
  fail "MongoDB port 27017 is published on the host"
fi
log "mongo_persistence=PASS"

PHASE="final"
cat > "${BASE}/aws-status.txt" <<EOF
SIMPLE BANK AWS BACKEND READY
source=${APP_SHA}
database=simple_bank_aws
mongo=PASS
mongo_replica_set=PASS
mongo_transactions=PASS
mongo_persistence=PASS
health=PASS
ready=PASS
admin=PASS
customer=PASS
bootstrap=OFF
demo_seed=OFF
EOF
chmod 644 "${BASE}/aws-status.txt"

log "========================================"
log "SIMPLE BANK AWS BACKEND READY"
log "========================================"
log "mongo=PASS"
log "mongo_replica_set=PASS"
log "mongo_transactions=PASS"
log "mongo_persistence=PASS"
log "health=PASS"
log "ready=PASS"
log "admin=PASS"
log "customer=PASS"
log "bootstrap=OFF"
log "demo_seed=OFF"
log "========================================"